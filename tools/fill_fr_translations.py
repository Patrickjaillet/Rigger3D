def main(folder: Path) -> int:
    missing = set()
    for lang in ("fr", "en"):
        path = folder / f"rigger_{lang}.ts"
        tree = ET.parse(path)
        for message in tree.getroot().iter("message"):
            source = message.find("source").text or ""
            translation = message.find("translation")
            if lang == "en":
                translation.text = source
                translation.attrib.pop("type", None)
                continue
            if source in FR:
                translation.text = FR[source]
                translation.attrib.pop("type", None)
            else:
                missing.add(source)
        ET.indent(tree, space="    ")
        tree.write(path, encoding="utf-8", xml_declaration=True)
        # ET écrit « <?xml version='1.0' encoding='utf-8'?> » et omet le DOCTYPE : on le rétablit.
        text = path.read_text(encoding="utf-8")
        text = text.replace("<?xml version='1.0' encoding='utf-8'?>", '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>')
        path.write_text(text, encoding="utf-8")
    for source in sorted(missing):
        print("NON TRADUIT :", repr(source))
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1] if len(sys.argv) > 1 else "assets/ui/i18n")))
